// 延时 10 us 函数
void delayus10(void)
{
    uchar i = 5;
    while(--i);
}

// 延时 10 ms 函数 (原书此处写为 delayms，实为粗略延时循环)
void delayms(uint j)
{
    uchar i = 250;
    for(; j > 0; j--)
    {
        while(--i); i = 249; while(--i); i = 250;
    }
}

// 屏幕选择: cs=0 选择双屏, cs=1 选择左半屏, cs=2 选择右半屏
void select(uchar cs)
{
    if(cs == 0)      { cs1 = 1; cs2 = 1; }
    else if(cs == 1) { cs1 = 1; cs2 = 0; }
    else             { cs1 = 0; cs2 = 1; }
}

// 写命令函数
void send_cmd(uchar cmd)
{
    rs = 0; rw = 0; bus = cmd; delayus10(); e = 1; e = 0;
}

// 写数据函数
void send_data(uchar dat)
{
    rs = 1; rw = 0; bus = dat; delayus10(); e = 1; e = 0;
}

// 清屏函数
void clear_screen(void)
{
    uchar c_page, c_column;
    select(0);
    for(c_page = 0; c_page < c_page_max; c_page++)
    {
        send_cmd(c_page + lcdpage);
        send_cmd(lcdcolumn);
        for(c_column = 0; c_column < c_column_max; c_column++)
        {
            send_data(0x00);
        }
    }
}

// LCD 初始化函数
void initial(void)
{
    select(0);
    rst = 0; delayms(10); rst = 1;
    clear_screen();
    send_cmd(lcdrow);
    send_cmd(lcdcolumn);
    send_cmd(lcdpage);
    send_cmd(0x3F);
}

// 写字符: c_page 为当前页, c_column 为当前列, num 为字符数, offset 为所取字符在缓冲区中的偏移单位
void display_zf(uchar c_page, uchar c_column, uchar num, uchar offset)
{
    uchar c1, c2, c3;
    for(c1 = 0; c1 < num; c1++)
    {
        for(c2 = 0; c2 < 2; c2++)
        {
            for(c3 = 0; c3 < 8; c3++)
            {
                send_cmd(lcdpage + c_page + c2);
                send_cmd(lcdcolumn + c_column + c1 * 8 + c3);
                send_data(table_zf[(c1 + offset) * 16 + c2 * 8 + c3]);
            }
        }
    }
}

// 写汉字: c_page 为当前页, c_column 为当前列, num 为字符数, offset 为所取汉字在缓冲区中的偏移单位
void display_hz(uchar c_page, uchar c_column, uchar num, uchar offset)
{
    uchar c1, c2, c3;
    for(c1 = 0; c1 < num; c1++)
    {
        for(c2 = 0; c2 < 2; c2++)
        {
            for(c3 = 0; c3 < 16; c3++)
            {
                send_cmd(lcdpage + c_page + c2);
                send_cmd(lcdcolumn + c_column + c1 * 16 + c3);
                send_data(table_hz[(c1 + offset) * 32 + c2 * 16 + c3]);
            }
        }
    }
}

// 在 LCD 上显示函数
void display(void)
{
    select(1);
    display_zf(0, 40, 3, 0); // 显示 "PRO"
    display_hz(2, 0, 4, 0);  // 显示 "电子设计"
    display_hz(4, 32, 2, 8); // 显示 "最佳"

    select(2);
    display_zf(0, 0, 4, 3);  // 显示 "TEUS"
    display_hz(2, 0, 4, 4);  // 显示 "与创新的"
    display_hz(4, 0, 2, 10); // 显示 "平台"
}

void main(void)
{
    initial();
    display();
    clear_screen();
    display();
    while(1);
}